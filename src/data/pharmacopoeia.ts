/**
 * 智能药典数据检索助手
 */
export function getHerbPharmInfo(name: string): HerbPharmacopoeiaInfo {
  const clean = name.trim();
  if (PHARMACOPOEIA_DATABASE[clean]) {
    return PHARMACOPOEIA_DATABASE[clean];
  }
  // Try sub-herbs if name contains punctuation
  const subNames = clean.split(/[\/、，·\s\+]/).map((s) => s.trim()).filter(Boolean);
  for (const sn of subNames) {
    if (PHARMACOPOEIA_DATABASE[sn]) {
      return PHARMACOPOEIA_DATABASE[sn];
    }
  }
  return {
    natureFlavor: '辛、苦，平',
    channelTropism: '归肺、脾、肝经',
  };
}

